import { useEffect, useState, useRef } from "react";
import { Link } from "react-router-dom";
import "./ContactCTA.css";

function ContactCTA() {
  const [mousePosition, setMousePosition] = useState({ x: 0.5, y: 0.5 });
  const [isVisible, setIsVisible] = useState(false);
  const sectionRef = useRef(null);

  useEffect(() => {
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) setIsVisible(true);
      },
      { threshold: 0.2 }
    );

    if (sectionRef.current) observer.observe(sectionRef.current);
    return () => observer.disconnect();
  }, []);

  useEffect(() => {
    const handleMouseMove = (e) => {
      if (sectionRef.current) {
        const rect = sectionRef.current.getBoundingClientRect();
        setMousePosition({
          x: (e.clientX - rect.left) / rect.width,
          y: (e.clientY - rect.top) / rect.height,
        });
      }
    };

    window.addEventListener("mousemove", handleMouseMove, { passive: true });
    return () => window.removeEventListener("mousemove", handleMouseMove);
  }, []);

  return (
    <section
      ref={sectionRef}
      className={`cta-premium ${isVisible ? "cta-visible" : ""}`}
      style={{
        "--mouse-x": mousePosition.x,
        "--mouse-y": mousePosition.y,
      }}
    >
      {/* Atmospheric Depth */}
      <div className="cta-atmosphere" aria-hidden="true">
        <div className="cta-glow cta-glow--teal" />
        <div className="cta-glow cta-glow--blue" />
        <div className="cta-glow cta-glow--emerald" />
        <div className="cta-mesh" />
        <div className="cta-grain" />
      </div>

      {/* Floating Glass Orbs */}
      <div className="cta-orbs" aria-hidden="true">
        <div className="cta-orb cta-orb--primary" />
        <div className="cta-orb cta-orb--secondary" />
        <div className="cta-orb cta-orb--tertiary" />
      </div>

      {/* Decorative Thread Lines */}
      <div className="cta-threads" aria-hidden="true">
        <div className="cta-thread cta-thread--one" />
        <div className="cta-thread cta-thread--two" />
        <div className="cta-thread cta-thread--three" />
      </div>

      <div className="cta-container">
        <div className="cta-content">
          {/* Whisper Label */}
          <div className="cta-whisper">
            <span className="cta-whisper-pulse" />
            <span>Begin your journey</span>
          </div>

          {/* Headline */}
          <h2 className="cta-headline">
            <span className="cta-headline-line">Elevate your experiences,</span>
            <span className="cta-headline-line cta-headline-radiance">
              embrace conscious living.
            </span>
          </h2>

          {/* Description */}
          <p className="cta-prose">
            Whether you seek unforgettable gatherings or nature's finest 
            organic provisions — we are here to guide every step of your 
            journey toward a richer, healthier life.
          </p>

          {/* Action Buttons */}
          <div className="cta-actions">
            <Link to="/events" className="cta-btn cta-btn-primary">
              <span>Explore Events</span>
              <span className="cta-btn-arrow">→</span>
              <div className="cta-btn-shimmer" aria-hidden="true" />
            </Link>

            <Link to="/products" className="cta-btn cta-btn-secondary">
              <span>Discover Products</span>
              <span className="cta-btn-arrow">→</span>
              <div className="cta-btn-shimmer" aria-hidden="true" />
            </Link>
          </div>

          {/* Essence Strip */}
          <div className="cta-essence">
            <div className="cta-essence-thread" />
            <div className="cta-essence-items">
              <div className="cta-essence-item">
                <span className="cta-essence-word">Verified</span>
                <span className="cta-essence-subtle">Trusted experiences</span>
              </div>
              <div className="cta-essence-separator" />
              <div className="cta-essence-item">
                <span className="cta-essence-word">Organic</span>
                <span className="cta-essence-subtle">Certified purity</span>
              </div>
              <div className="cta-essence-separator" />
              <div className="cta-essence-item">
                <span className="cta-essence-word">Secure</span>
                <span className="cta-essence-subtle">Protected always</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}

export default ContactCTA;